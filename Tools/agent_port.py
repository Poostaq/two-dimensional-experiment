from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Dict, Iterable, List, Mapping, Sequence, Tuple


SCHEMA_VERSION = 1
REQUIRED_ROLE_FIELDS = (
	"schema_version",
	"id",
	"display_name",
	"description",
	"write_policy",
	"capabilities",
	"skills",
)
WRITE_POLICIES = {"read_only", "workspace_write"}
WRITE_CAPABILITIES = {"repo.edit", "repo.execute", "godot.scene_edit"}
PROHIBITED_CANONICAL_TEXT = (
	"AskUserQuestion",
	"TodoWrite",
	"Task tool",
	".claude/",
	"CLAUDE.md",
)
GENERATED_NOTICE = "Generated by tools/agent_port.py. Do not edit directly."
ROLE_ID_PATTERN = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")


def _read_json(path: Path) -> object:
	with path.open("r", encoding="utf-8") as file_handle:
		return json.load(file_handle)


def _read_text(path: Path) -> str:
	return path.read_text(encoding="utf-8").replace("\r\n", "\n")


def _write_text(path: Path, content: str) -> None:
	path.parent.mkdir(parents=True, exist_ok=True)
	with path.open("w", encoding="utf-8", newline="\n") as file_handle:
		file_handle.write(content)


def _skill_names(root: Path) -> Tuple[set[str], List[str]]:
	errors: List[str] = []
	names: set[str] = set()
	skills_root = root / ".agents" / "skills"
	if not skills_root.is_dir():
		return names, ["missing skills directory: .agents/skills"]
	for skill_path in sorted(skills_root.glob("*/SKILL.md")):
		folder_name = skill_path.parent.name
		content = _read_text(skill_path)
		match = re.match(r"^---\n(.*?)\n---\n", content, flags=re.DOTALL)
		if match is None:
			errors.append(f"{skill_path.relative_to(root)}: missing YAML frontmatter")
			continue
		frontmatter = match.group(1)
		name_match = re.search(r"^name:\s*([^\n]+)$", frontmatter, flags=re.MULTILINE)
		description_match = re.search(r"^description:\s*([^\n]+)$", frontmatter, flags=re.MULTILINE)
		if name_match is None:
			errors.append(f"{skill_path.relative_to(root)}: missing skill name")
			continue
		name = name_match.group(1).strip().strip('"\'')
		if description_match is None:
			errors.append(f"{skill_path.relative_to(root)}: missing skill description")
		if name != folder_name:
			errors.append(f"{skill_path.relative_to(root)}: skill name must match directory")
		if name in names:
			errors.append(f"duplicate skill name: {name}")
		names.add(name)
		for prohibited in PROHIBITED_CANONICAL_TEXT:
			if prohibited in content:
				errors.append(f"{skill_path.relative_to(root)}: prohibited platform term: {prohibited}")
	return names, errors


def _capability_map(root: Path) -> Tuple[Dict[str, Mapping[str, object]], List[str]]:
	path = root / ".agents" / "platforms" / "capabilities.json"
	if not path.is_file():
		return {}, ["missing capability map: .agents/platforms/capabilities.json"]
	try:
		payload = _read_json(path)
	except (OSError, json.JSONDecodeError) as error:
		return {}, [f"{path.relative_to(root)}: invalid JSON: {error}"]
	if not isinstance(payload, dict) or payload.get("schema_version") != SCHEMA_VERSION:
		return {}, [f"{path.relative_to(root)}: invalid schema_version"]
	capabilities = payload.get("capabilities")
	if not isinstance(capabilities, dict):
		return {}, [f"{path.relative_to(root)}: capabilities must be an object"]
	errors: List[str] = []
	result: Dict[str, Mapping[str, object]] = {}
	for capability, mapping in sorted(capabilities.items()):
		if not isinstance(capability, str) or not isinstance(mapping, dict):
			errors.append(f"{path.relative_to(root)}: invalid capability mapping")
			continue
		tools = mapping.get("copilot_tools")
		if not isinstance(tools, list) or not all(isinstance(tool, str) for tool in tools):
			errors.append(f"{path.relative_to(root)}: {capability} requires copilot_tools")
			continue
		result[capability] = mapping
	return result, errors


def _load_roles(root: Path) -> Tuple[List[Mapping[str, object]], List[str]]:
	errors: List[str] = []
	roles: List[Mapping[str, object]] = []
	seen_ids: set[str] = set()
	roles_root = root / ".agents" / "roles"
	if not roles_root.is_dir():
		return roles, ["missing roles directory: .agents/roles"]
	for manifest_path in sorted(roles_root.glob("*/agent.json")):
		relative_path = manifest_path.relative_to(root)
		try:
			manifest = _read_json(manifest_path)
		except (OSError, json.JSONDecodeError) as error:
			errors.append(f"{relative_path}: invalid JSON: {error}")
			continue
		if not isinstance(manifest, dict):
			errors.append(f"{relative_path}: manifest must be an object")
			continue
		for field in REQUIRED_ROLE_FIELDS:
			if field not in manifest:
				errors.append(f"{relative_path}: missing required field: {field}")
		role_id = manifest.get("id")
		if not isinstance(role_id, str) or ROLE_ID_PATTERN.fullmatch(role_id) is None:
			errors.append(f"{relative_path}: invalid role id")
		else:
			if role_id in seen_ids:
				errors.append(f"duplicate role id: {role_id}")
			seen_ids.add(role_id)
			if role_id != manifest_path.parent.name:
				errors.append(f"{relative_path}: role id must match directory")
		instructions_path = manifest_path.parent / "instructions.md"
		if not instructions_path.is_file():
			errors.append(f"{relative_path}: missing instructions.md")
		else:
			instructions = _read_text(instructions_path)
			for prohibited in PROHIBITED_CANONICAL_TEXT:
				if prohibited in instructions:
					errors.append(f"{instructions_path.relative_to(root)}: prohibited platform term: {prohibited}")
		roles.append(manifest)
	return sorted(roles, key=lambda role: str(role.get("id", ""))), errors


def validate_repository(root: Path) -> List[str]:
	root = root.resolve()
	errors: List[str] = []
	skills, skill_errors = _skill_names(root)
	capabilities, capability_errors = _capability_map(root)
	roles, role_errors = _load_roles(root)
	errors.extend(skill_errors)
	errors.extend(capability_errors)
	errors.extend(role_errors)
	for role in roles:
		role_id = str(role.get("id", "<unknown>"))
		if role.get("schema_version") != SCHEMA_VERSION:
			errors.append(f"{role_id}: invalid schema_version")
		for field in ("display_name", "description"):
			if field in role and (not isinstance(role[field], str) or not str(role[field]).strip()):
				errors.append(f"{role_id}: {field} must be a non-empty string")
		write_policy = role.get("write_policy")
		if write_policy not in WRITE_POLICIES:
			errors.append(f"{role_id}: invalid write_policy: {write_policy}")
		role_capabilities = role.get("capabilities")
		if not isinstance(role_capabilities, list) or not all(isinstance(item, str) for item in role_capabilities):
			errors.append(f"{role_id}: capabilities must be a string array")
			role_capabilities = []
		for capability in role_capabilities:
			if capability not in capabilities:
				errors.append(f"{role_id}: unknown capability: {capability}")
		if write_policy == "read_only":
			for capability in sorted(set(role_capabilities) & WRITE_CAPABILITIES):
				errors.append(f"{role_id}: read_only role cannot use {capability}")
		role_skills = role.get("skills")
		if not isinstance(role_skills, list) or not all(isinstance(item, str) for item in role_skills):
			errors.append(f"{role_id}: skills must be a string array")
			role_skills = []
		for skill in role_skills:
			if skill not in skills:
				errors.append(f"{role_id}: unknown skill: {skill}")
	return sorted(set(errors))


def _copilot_tools(role: Mapping[str, object], capability_map: Mapping[str, Mapping[str, object]]) -> List[str]:
	tools: set[str] = set()
	for capability in role["capabilities"]:
		mapping = capability_map[str(capability)]
		tools.update(str(tool) for tool in mapping["copilot_tools"])
	if role["write_policy"] == "read_only":
		tools.discard("edit")
		tools.discard("execute")
	return sorted(tools)


def _role_instructions(root: Path, role_id: str) -> str:
	return _read_text(root / ".agents" / "roles" / role_id / "instructions.md").strip()


def _render_codex(root: Path, role: Mapping[str, object]) -> str:
	role_id = str(role["id"])
	sandbox_mode = "workspace-write" if role["write_policy"] == "workspace_write" else "read-only"
	skills = ", ".join(f"${skill}" for skill in role["skills"]) or "none"
	capabilities = ", ".join(str(item) for item in role["capabilities"])
	instructions = (
		f"{_role_instructions(root, role_id)}\n\n"
		f"Repository governance: read `.agents/policies/project-governance.md` before scoped work.\n"
		f"Declared capabilities: {capabilities}.\n"
		f"Relevant shared skills: {skills}."
	)
	return (
		f"# {GENERATED_NOTICE}\n"
		f"name = {json.dumps(role_id, ensure_ascii=False)}\n"
		f"description = {json.dumps(str(role['description']), ensure_ascii=False)}\n"
		f"sandbox_mode = {json.dumps(sandbox_mode)}\n"
		f"developer_instructions = {json.dumps(instructions, ensure_ascii=False)}\n"
	)


def _render_copilot(
	root: Path,
	role: Mapping[str, object],
	capability_map: Mapping[str, Mapping[str, object]],
) -> str:
	role_id = str(role["id"])
	tools = _copilot_tools(role, capability_map)
	tool_lines = "".join(f"  - {tool}\n" for tool in tools)
	skills = "\n".join(f"- `{skill}`" for skill in role["skills"]) or "- None"
	return (
		"---\n"
		f"name: {json.dumps(str(role['display_name']), ensure_ascii=False)}\n"
		f"description: {json.dumps(str(role['description']), ensure_ascii=False)}\n"
		"tools:\n"
		f"{tool_lines}"
		"---\n"
		f"<!-- {GENERATED_NOTICE} -->\n\n"
		f"{_role_instructions(root, role_id)}\n\n"
		"## Repository integration\n\n"
		"Read `.agents/policies/project-governance.md` before scoped work and honor `AGENTS.md`.\n\n"
		"Relevant shared skills:\n\n"
		f"{skills}\n"
	)


def render_adapters(root: Path) -> Dict[Path, str]:
	root = root.resolve()
	errors = validate_repository(root)
	if errors:
		raise ValueError("\n".join(errors))
	capability_map, _ = _capability_map(root)
	roles, _ = _load_roles(root)
	result: Dict[Path, str] = {}
	for role in roles:
		role_id = str(role["id"])
		result[Path(f".codex/agents/{role_id}.toml")] = _render_codex(root, role)
	for role in roles:
		role_id = str(role["id"])
		result[Path(f".github/agents/{role_id}.agent.md")] = _render_copilot(root, role, capability_map)
	return result


def generate_adapters(root: Path) -> List[Path]:
	rendered = render_adapters(root)
	for relative_path, content in rendered.items():
		_write_text(root / relative_path, content)
	return list(rendered)


def _generated_files(root: Path) -> Iterable[Path]:
	for directory, pattern in ((root / ".codex" / "agents", "*.toml"), (root / ".github" / "agents", "*.agent.md")):
		if not directory.is_dir():
			continue
		for path in directory.glob(pattern):
			if GENERATED_NOTICE in _read_text(path):
				yield path.relative_to(root)


def check_adapters(root: Path) -> List[Path]:
	rendered = render_adapters(root)
	drift: set[Path] = set()
	for relative_path, expected in rendered.items():
		path = root / relative_path
		if not path.is_file() or _read_text(path) != expected:
			drift.add(relative_path)
	drift.update(set(_generated_files(root)) - set(rendered))
	return sorted(drift, key=lambda path: path.as_posix())


def _build_parser() -> argparse.ArgumentParser:
	parser = argparse.ArgumentParser(description="Validate and generate platform agent adapters.")
	parser.add_argument("command", choices=("validate", "generate", "check"))
	parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
	return parser


def main(argv: Sequence[str] | None = None) -> int:
	args = _build_parser().parse_args(argv)
	root = args.root.resolve()
	errors = validate_repository(root)
	if errors:
		for error in errors:
			print(f"validation error: {error}")
		return 1
	if args.command == "validate":
		print("agent catalog valid")
		return 0
	if args.command == "generate":
		for path in generate_adapters(root):
			print(f"generated {path.as_posix()}")
		return 0
	drift = check_adapters(root)
	if drift:
		for path in drift:
			print(f"stale adapter: {path.as_posix()}")
		return 1
	print("generated adapters are current")
	return 0


if __name__ == "__main__":
	sys.exit(main())
